/**
 * Key layout for per-user files in the file bucket.
 *
 * Every object a user creates through the application lives under
 * `users/<userId>/`, so whether a caller may read or delete an object follows
 * from its key: the owner is the first path segment. Keys outside this layout
 * (files from earlier versions) are not served. Access through a share is
 * decided by `canAccessFile` in `chat-files.ts`.
 *
 * `<userId>` is the user's Cognito `sub`, taken from the verified id token. It
 * names no one, so keys, signed URLs and S3 logs carry no user name or email
 * address. The segment is URI-encoded so that no id can add path syntax.
 */

export const USER_FILE_PREFIX = 'users/';

const ATTACHMENTS = 'attachments';
const VIDEOS = 'videos';
const AGENT_OUTPUTS = 'agent-outputs';

/** `users/<encoded userId>/` */
export const userFilePrefix = (userId: string): string =>
  `${USER_FILE_PREFIX}${encodeURIComponent(userId)}/`;

const MAX_FILE_NAME_LENGTH = 200;

/**
 * Reduce a client-supplied file name to a single safe path segment.
 *
 * Directory parts are dropped, control characters removed, and names that are
 * empty or consist only of dots are replaced, so the result can never move the
 * key out of the directory the server chose.
 */
export const sanitizeFileName = (name: string): string => {
  const base = (name ?? '').split(/[/\\]/).pop() ?? '';
  // eslint-disable-next-line no-control-regex
  const cleaned = base.replace(/[\u0000-\u001f\u007f]/g, '').trim();
  const limited = cleaned.slice(-MAX_FILE_NAME_LENGTH);
  return limited === '' || /^\.+$/.test(limited) ? 'file' : limited;
};

/** Key for a new chat attachment. `uuid` is generated by the server. */
export const attachmentKey = (
  userId: string,
  uuid: string,
  fileName: string
): string =>
  `${userFilePrefix(userId)}${ATTACHMENTS}/${uuid}/${sanitizeFileName(fileName)}`;

/** Key of a generated video once it is copied into the file bucket. */
export const videoOutputKey = (userId: string, jobId: string): string =>
  `${userFilePrefix(userId)}${VIDEOS}/${jobId}/output.mp4`;

/** Key of a file produced by a Bedrock Agent for the user. */
export const agentOutputKey = (
  userId: string,
  uuid: string,
  fileName: string
): string =>
  `${userFilePrefix(userId)}${AGENT_OUTPUTS}/${uuid}/${sanitizeFileName(fileName)}`;

/** True when the key has no empty, `.` or `..` segments. */
export const isNormalizedKey = (key: string): boolean =>
  key.length > 0 &&
  !key.startsWith('/') &&
  key.split('/').every((s) => s !== '' && s !== '.' && s !== '..');

/** True when `key` is a normalized key under the user's own prefix. */
export const isOwnedFileKey = (userId: string, key: string): boolean =>
  isNormalizedKey(key) &&
  key.startsWith(userFilePrefix(userId)) &&
  key.length > userFilePrefix(userId).length;

/** The owner encoded in `users/<owner>/...`, or null for any other key. */
export const userFileOwner = (key: string): string | null => {
  if (!isNormalizedKey(key) || !key.startsWith(USER_FILE_PREFIX)) return null;
  const segments = key.slice(USER_FILE_PREFIX.length).split('/');
  // Owner segment plus at least one more segment.
  if (segments.length < 2) return null;
  try {
    const owner = decodeURIComponent(segments[0]);
    // Only the canonical encoding written by `userFilePrefix` names an owner.
    if (owner === '' || encodeURIComponent(owner) !== segments[0]) return null;
    return owner;
  } catch {
    return null;
  }
};

export type S3ObjectLocation = {
  bucket: string;
  key: string;
  region?: string;
};

/**
 * Parse `s3://bucket/key`, a virtual-hosted URL
 * (`https://bucket.s3[.-]region.amazonaws.com/key`) or a path-style URL
 * (`https://s3.region.amazonaws.com/bucket/key`). The key is URI-decoded and a
 * query string or fragment is ignored. Returns null for anything else.
 */
export const parseS3ObjectUrl = (url: string): S3ObjectLocation | null => {
  const decode = (raw: string): string | null => {
    try {
      return decodeURIComponent(raw);
    } catch {
      return null;
    }
  };

  const s3Uri = /^s3:\/\/([^/]+)\/(.+)$/.exec(url);
  if (s3Uri) {
    return { bucket: s3Uri[1], key: s3Uri[2] };
  }

  let parsed: URL;
  try {
    parsed = new URL(url);
  } catch {
    return null;
  }
  if (parsed.protocol !== 'https:') return null;

  const path = parsed.pathname.replace(/^\//, '');
  const host = parsed.hostname;

  const pathStyle = /^s3[.-]([a-z0-9-]+)\.amazonaws\.com$/.exec(host);
  if (pathStyle) {
    const slash = path.indexOf('/');
    if (slash <= 0) return null;
    const key = decode(path.slice(slash + 1));
    return key
      ? { bucket: path.slice(0, slash), key, region: pathStyle[1] }
      : null;
  }

  const virtual = /^(.+?)\.s3(?:[.-]([a-z0-9-]+))?\.amazonaws\.com$/.exec(host);
  if (virtual && path) {
    const key = decode(path);
    return key ? { bucket: virtual[1], key, region: virtual[2] } : null;
  }

  return null;
};
