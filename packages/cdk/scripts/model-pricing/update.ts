// Usage (from packages/cdk): npm run pricing:update [-- --from <dir>] [-- --force]
//
// Fetches the public AWS Price List bulk files for Amazon Bedrock and writes
// lambda/utils/modelPricing.generated.ts, the list prices the admin page uses
// for its cost estimate. Run it when adding models or before a release, and
// review the diff. Nothing calls the price list at deploy or run time.
//
// --from <dir>  read <dir>/<OfferName>-<region>.json instead of downloading
// --force       write even when far fewer models are priced than before
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { modelMetadata } from '@generative-ai-use-cases/common';
import { ModelPrices } from 'generative-ai-use-cases';
import { extractPrices, normalizeName, OfferFile } from './extract';

// Regions GenU is commonly deployed with as modelRegion / model regions.
// Add a Region here when a deployment uses models from it.
export const REGIONS = [
  'us-east-1',
  'us-east-2',
  'us-west-2',
  'ap-northeast-1',
  'ap-northeast-2',
  'ap-northeast-3',
  'ap-south-1',
  'ap-southeast-1',
  'ap-southeast-2',
  'ca-central-1',
  'eu-central-1',
  'eu-north-1',
  'eu-west-1',
  'eu-west-2',
  'eu-west-3',
  'sa-east-1',
];
const OFFERS = ['AmazonBedrock', 'AmazonBedrockFoundationModels'];

// GenU display name -> price list name, where the two name a model differently.
export const ALIASES: Record<string, string> = {
  'Nova Lite 2': 'Nova 2.0 Lite',
  'Ministral 3 3B': 'Ministral 3B 3.0',
  'Ministral 3 8B': 'Ministral 8B 3.0',
  'Ministral 3 14B': 'Ministral 14B 3.0',
  'Magistral Small 2509': 'Magistral Small 1.2',
  'NVIDIA Nemotron Nano 9B v2': 'NVIDIA Nemotron Nano 2',
  'NVIDIA Nemotron Nano 12B v2 VL BF16': 'NVIDIA Nemotron Nano 2 VL',
  'Pixtral Large (25.02)': 'Pixtral Large 25.02',
  'Mistral Large 2 (24.07)': 'Mistral Large 2407',
};
const OUTPUT = join(__dirname, '../../lambda/utils/modelPricing.generated.ts');

const args = process.argv.slice(2);
const fromDir = args.includes('--from')
  ? args[args.indexOf('--from') + 1]
  : undefined;
const force = args.includes('--force');

const loadOffer = async (offer: string, region: string): Promise<OfferFile> => {
  if (fromDir) {
    return JSON.parse(
      readFileSync(join(fromDir, `${offer}-${region}.json`), 'utf8')
    );
  }
  const url = `https://pricing.us-east-1.amazonaws.com/offers/v1.0/aws/${offer}/current/${region}/index.json`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return (await res.json()) as OfferFile;
};

/** Display names of the text models GenU defines (what Stats records). */
const textModelNames = (): string[] => [
  ...new Set(
    Object.values(modelMetadata)
      .filter((meta) => meta.flags.text)
      .map((meta) => meta.displayName)
  ),
];

/**
 * Priced (Region, model, scope) entries in a generated file, before or after
 * prettier (which drops the quotes around `regional` and `global`).
 */
export const countPriced = (source: string): number =>
  (source.match(/^\s*"?(regional|global)"?:/gm) ?? []).length;

const main = async () => {
  const names = textModelNames();
  const byRegion: Record<string, Record<string, ModelPrices>> = {};
  const unmatched = new Map<string, string[]>();

  for (const region of REGIONS) {
    const offers = await Promise.all(
      OFFERS.map((offer) => loadOffer(offer, region))
    );
    const { prices, conflicts } = extractPrices(offers);
    if (conflicts.length > 0) {
      console.warn(`${region}: conflicting prices, skipped:`, conflicts);
    }
    const regionPrices: Record<string, ModelPrices> = {};
    for (const name of names) {
      const price = prices.get(normalizeName(ALIASES[name] ?? name));
      if (price) regionPrices[name] = price;
      else unmatched.set(name, [...(unmatched.get(name) ?? []), region]);
    }
    byRegion[region] = regionPrices;
    console.log(`${region}: ${Object.keys(regionPrices).length} models`);
  }

  // Models priced in no Region at all are most likely a name mismatch.
  const nowhere = [...unmatched]
    .filter(([, regions]) => regions.length === REGIONS.length)
    .map(([name]) => name)
    .sort();
  if (nowhere.length > 0) {
    console.warn('No price in any Region (check the name):', nowhere);
  }

  const date = new Date().toISOString().slice(0, 10);
  const body = JSON.stringify(byRegion, null, 2);
  const source = `// Generated by scripts/model-pricing/update.ts. Do not edit by hand.
// List prices from the AWS Price List bulk API, USD per 1,000 tokens, on-demand.
// Region -> model display name -> { regional (in-Region and geographic
// cross-Region inference), global (global cross-Region inference) }.
import { ModelPrices } from 'generative-ai-use-cases';

export const MODEL_PRICING_DATE = '${date}';

export const MODEL_PRICING: Record<string, Record<string, ModelPrices>> = ${body};
`;

  if (existsSync(OUTPUT) && !force) {
    const before = countPriced(readFileSync(OUTPUT, 'utf8'));
    const after = countPriced(source);
    if (before > 0 && after < before * 0.8) {
      throw new Error(
        `Priced entries dropped from ${before} to ${after}; the price list format may have changed. Check it, then rerun with --force.`
      );
    }
  }
  writeFileSync(OUTPUT, source);
  console.log(`Wrote ${OUTPUT}`);
};

if (require.main === module) {
  main().catch((error) => {
    console.error(error);
    process.exit(1);
  });
}
